const evidence = []
let updatedEmployeePassword
function record(name, condition) { evidence.push({ case: name, pass: Boolean(condition) }); expect(Boolean(condition), name).toBe(true) }
beforeAll(async () => {
  localStorage.setItem('castravision_language', 'vi')
  const { data, error } = await supabase.auth.signInWithPassword({ email: process.env.EMPLOYEE_EMAIL, password: process.env.EMPLOYEE_PASSWORD })
  if (error) throw new Error('Disposable local Employee login failed')
  setActiveWorkspaceId(data.user.id, process.env.EMPLOYEE_WORKSPACE)
})
afterAll(async () => {
  await supabase.auth.signOut({ scope: 'local' })
  writeFileSync('../docs/UI/audits/2026-11-20/employee-remediation-ui.json', JSON.stringify(evidence, null, 2))
  writeFileSync('../docs/UI/audits/2026-11-20/employee-remediation-transport.json', JSON.stringify(globalThis.__employeeAuditRequests, null, 2))
})

