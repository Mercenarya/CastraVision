test('Leader assigns in real UI and Employee receives task', async () => {
  cleanup()
  const user = userEvent.setup()
  const login = async (email, password) => {
    const result = await supabase.auth.signInWithPassword({ email, password })
    if (result.error) throw new Error('Disposable role login failed')
    // Audit only: local Docker and Windows clocks can disagree on a brand-new iat.
    // Do not alter production Auth or silently retry a product request.
    await new Promise(resolve => setTimeout(resolve, 2000))
    setActiveWorkspaceId(result.data.user.id, process.env.EMPLOYEE_WORKSPACE)
  }
  await login(process.env.LEADER_EMAIL, process.env.LEADER_PASSWORD)
  render(<App />)
  await waitFor(() => expect(document.querySelector('nav')?.querySelectorAll('button').length || 0).toBeGreaterThan(3), { timeout: 30000 })
  await user.click(document.querySelector('nav').querySelectorAll('button')[3])
  await user.click(await screen.findByRole('button', { name: 'Giao nhiệm vụ trong Team' }, { timeout: 20000 }))
  await waitFor(() => expect(screen.getByRole('button', { name: 'Giao nhiệm vụ', exact: true }).disabled).toBe(false), { timeout: 15000 })
  await user.click(screen.getByRole('button', { name: 'Giao nhiệm vụ', exact: true }))
  await waitFor(() => expect(screen.getByLabelText('Chiến dịch nhận việc').options.length).toBeGreaterThan(1), { timeout: 15000 })
  await user.selectOptions(screen.getByLabelText('Chiến dịch nhận việc'), Array.from(screen.getByLabelText('Chiến dịch nhận việc').options).find(option => option.textContent === 'Employee Audit Campaign').value)
  await waitFor(() => expect(Array.from(screen.getByLabelText('Nhân viên được giao').options).some(option => option.value === process.env.EMPLOYEE_USER_ID)).toBe(true), { timeout: 15000 })
  await user.selectOptions(screen.getByLabelText('Nhân viên được giao'), process.env.EMPLOYEE_USER_ID)
  await user.type(screen.getByLabelText('Tên nhiệm vụ'), 'UI Leader Assigned Task')
  await user.click(screen.getByRole('button', { name: 'Giao việc', exact: true }))
  await waitFor(() => expect(screen.queryByRole('heading', { name: 'UI Leader Assigned Task' })).toBeTruthy(), { timeout: 15000 })
  record('Leader assignment form persists real task', true)
  cleanup()
  await supabase.auth.signOut({ scope: 'local' })
  await login(process.env.EMPLOYEE_EMAIL, updatedEmployeePassword)
  render(<App />)
  await waitFor(() => expect(document.querySelector('nav')?.querySelectorAll('button').length).toBeGreaterThan(1), { timeout: 30000 })
  await user.click(document.querySelector('nav').querySelectorAll('button')[1])
  await waitFor(() => expect(screen.queryByText('UI Leader Assigned Task')).toBeTruthy(), { timeout: 15000 })
  record('Employee receives Leader UI assignment without assign permission', !screen.queryByRole('button', { name: 'Giao nhiệm vụ', exact: true }))
  await user.click(screen.getByText('UI Leader Assigned Task').closest('article').querySelector('button'))
  await waitFor(() => expect(screen.queryByLabelText('Liên kết đề xuất của tôi')).toBeTruthy(), { timeout: 15000 })
  await waitFor(() => expect(Array.from(screen.getByLabelText('Liên kết đề xuất của tôi').options).some(option => option.textContent === 'Employee UI Created Draft')).toBe(true), { timeout: 15000 })
  await user.selectOptions(screen.getByLabelText('Liên kết đề xuất của tôi'), Array.from(screen.getByLabelText('Liên kết đề xuất của tôi').options).find(option => option.textContent === 'Employee UI Created Draft').value)
  await user.selectOptions(screen.getByLabelText('Trạng thái nhiệm vụ'), 'in_progress')
  await user.click(screen.getByRole('button', { name: 'Lưu nhiệm vụ' }))
  await user.click(await screen.findByRole('button', { name: 'Mở đề xuất liên kết' }, { timeout: 15000 }))
  await waitFor(() => expect(screen.queryByRole('heading', { name: 'Employee UI Created Draft' })).toBeTruthy(), { timeout: 15000 })
  record('Employee links and opens own persisted draft through task UI', true)
})

